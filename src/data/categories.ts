/**
 * Snaps any arbitrary candidate string strictly to an exact match in the authorized list.
 */
export function matchCategory(rawVal: string, customList?: string[]): string {
  if (!rawVal) return AUTHORIZED_CATEGORIES[0];
  const list = customList && customList.length > 0 ? customList : AUTHORIZED_CATEGORIES;
  const trimmed = rawVal.trim().replace(/^["']|["']$/g, "");

  // 1. Direct exact match
  const exact = list.find((c) => c === trimmed);
  if (exact) return exact;

  // 2. Case-insensitive match
  const ci = list.find((c) => c.toLowerCase() === trimmed.toLowerCase());
  if (ci) return ci;

  // 3. Normalized spaces around ">"
  const normTarget = trimmed.replace(/\s*>\s*/g, " > ").toLowerCase();
  const normMatch = list.find((c) => c.replace(/\s*>\s*/g, " > ").toLowerCase() === normTarget);
  if (normMatch) return normMatch;

  // 4. Match by leaf phrase
  const leafCandidate = trimmed.split(">").pop()?.trim().toLowerCase() || "";
  if (leafCandidate.length > 2) {
    const leafMatch = list.find((c) => {
      const cLeaf = c.split(">").pop()?.trim().toLowerCase() || "";
      return cLeaf === leafCandidate || cLeaf.includes(leafCandidate) || leafCandidate.includes(cLeaf);
    });
    if (leafMatch) return leafMatch;
  }

  // 5. Root domain match
  const rootCandidate = trimmed.split(">")[0]?.trim().toLowerCase() || "";
  const rootMatch = list.find((c) => c.toLowerCase().startsWith(rootCandidate));
  if (rootMatch) return rootMatch;

  return list[0];
}
