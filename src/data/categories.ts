/**
 * Normalizes and extracts the Root Category (e.g., "OTC Medications")
 */
export function getRootCategory(fullPath: string): string {
  if (!fullPath) return "";
  const parts = fullPath.split(">");
  return parts[0].trim();
}

/**
 * Normalizes and extracts the Leaf Category (e.g., "Fever and Pain-relief Medications")
 */
export function getLeafCategory(fullPath: string): string {
  if (!fullPath) return "";
  const parts = fullPath.split(">");
  return parts[parts.length - 1].trim();
}

